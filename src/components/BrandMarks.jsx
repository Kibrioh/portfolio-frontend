function IconLink({ href, label, children, ...props }) {
  if (!href) return null
  try {
    const url = new URL(href)
    if (url.pathname === '/' && !url.search && !url.hash) return null
  } catch { return null }
  return <a href={href} target="_blank" rel="noreferrer" aria-label={label} {...props}>{children}</a>
}

